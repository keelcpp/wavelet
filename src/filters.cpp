bool lookup_filters(StringRef name, FilterBank& out, Allocator* alloc) {
    if (name.empty()) return false;

    for (const OrthSpec& s : kOrthFamilies) {
        if (name == s.name) {
            const usize n = s.len;
            copy_to_array(out.lo_d, s.lo_d, n, alloc);
            out.lo_r = Array<f64>(alloc);
            out.hi_r = Array<f64>(alloc);
            out.hi_d = Array<f64>(alloc);
            out.lo_r.resize(n);
            out.hi_r.resize(n);
            out.hi_d.resize(n);
            for (usize k = 0; k < n; ++k) out.lo_r[k] = out.lo_d[n - 1 - k];
            for (usize k = 0; k < n; ++k) {
                const f64 sgn = ((k & 1u) == 0u) ? 1.0 : -1.0;
                out.hi_r[k] = sgn * out.lo_r[n - 1 - k];
            }
            for (usize k = 0; k < n; ++k) out.hi_d[k] = out.hi_r[n - 1 - k];
            return true;
        }
    }

    for (const BiorSpec& b : kBiorFamilies) {
        if (name == b.name) {
            copy_to_array(out.lo_d, b.lo_d, b.len, alloc);
            copy_to_array(out.hi_d, b.hi_d, b.len, alloc);
            copy_to_array(out.lo_r, b.lo_r, b.len, alloc);
            copy_to_array(out.hi_r, b.hi_r, b.len, alloc);
            return true;
        }
    }
    return false;
}

FilterBank orthfilt(ArrayRef<f64> scaling_w, Allocator* alloc) {
    FilterBank fb{Array<f64>(alloc), Array<f64>(alloc), Array<f64>(alloc), Array<f64>(alloc)};
    const usize n = scaling_w.size();
    if (n == 0) return fb;
    fb.lo_r.resize(n);
    fb.lo_d.resize(n);
    fb.hi_r.resize(n);
    fb.hi_d.resize(n);
    for (usize k = 0; k < n; ++k) fb.lo_r[k] = scaling_w[k] * kSqrt2;
    for (usize k = 0; k < n; ++k) fb.lo_d[k] = fb.lo_r[n - 1 - k];
    for (usize k = 0; k < n; ++k) {
        const f64 sgn = ((k & 1u) == 0u) ? 1.0 : -1.0;
        fb.hi_r[k] = sgn * fb.lo_r[n - 1 - k];
    }
    for (usize k = 0; k < n; ++k) fb.hi_d[k] = fb.hi_r[n - 1 - k];
    return fb;
}

void qmf(ArrayRef<f64> x, MutArrayRef<f64> out, i32 parity) noexcept {
    const usize n = min(x.size(), out.size());
    const i32 p = ((parity % 2) + 2) % 2;
    for (usize k = 0; k < n; ++k) {
        const f64 v = x[n - 1 - k];
        const bool neg = ((k & 1u) == 1u);
        out[k] = (neg ^ (p == 1)) ? -v : v;
    }
}

